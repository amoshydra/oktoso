import { dirname, resolve } from "node:path";
import { mkdir } from "node:fs/promises";
import type { Browser, Page } from "playwright";
import {
  captureAt,
  captureClock,
  launchBrandBrowser,
  manifestPath,
  newBrandPage,
  outputSpecs,
  repoRoot,
  settle,
  sha256File,
  sourceFiles,
  startStaticServer,
  writeManifest,
  type BrandManifest,
  type BrandOutput,
} from "./common";

async function capturePrototype(
  browser: Browser,
  resizePage: Page,
  base: string,
  mode: "inbox" | "session",
  viewport: { width: number; height: number },
  output: string,
): Promise<BrandOutput> {
  const page = await newBrandPage(browser, viewport);
  await page.goto(`${base}/docs/prototypes/?capture=${mode}`, {
    waitUntil: "networkidle",
  });
  await page.waitForFunction(
    (expected) => document.documentElement.dataset.capture === expected,
    mode,
  );
  if (mode === "session") {
    await page.waitForFunction(
      () =>
        document
          .querySelector(".chat-session-title")
          ?.textContent?.includes("Fix auth race in gateway") === true,
    );
    await page.waitForFunction(() => {
      const transcript = document.getElementById("transcript");
      return transcript !== null && transcript.scrollTop === 0;
    });
  }
  await settle(page);
  const result = await captureAt(
    page,
    resizePage,
    output,
    viewport.width,
    viewport.height,
  );
  await page.close();
  return result;
}

async function captureBanner(
  browser: Browser,
  resizePage: Page,
  base: string,
): Promise<BrandOutput> {
  const viewport = { width: 1600, height: 560 };
  const page = await newBrandPage(browser, viewport);
  await page.goto(`${base}/docs/brand/banner.html`, {
    waitUntil: "networkidle",
  });
  await page.waitForFunction(() =>
    Array.from(document.images).every(
      (image) => image.complete && image.naturalWidth > 0,
    ),
  );
  await settle(page);
  const result = await captureAt(
    page,
    resizePage,
    "docs/brand/banner.png",
    viewport.width,
    viewport.height,
  );
  await page.close();
  return result;
}

const server = await startStaticServer(repoRoot);
const browser = await launchBrandBrowser();
const resizePage = await newBrandPage(browser, { width: 1600, height: 560 });

try {
  const inbox = await capturePrototype(
    browser,
    resizePage,
    server.base,
    "inbox",
    { width: 1440, height: 900 },
    "docs/screenshots/inbox.png",
  );
  const session = await capturePrototype(
    browser,
    resizePage,
    server.base,
    "session",
    { width: 1440, height: 1100 },
    "docs/screenshots/session.png",
  );
  const banner = await captureBanner(browser, resizePage, server.base);

  const sources: Record<string, string> = {};
  for (const file of await sourceFiles()) {
    sources[file] = await sha256File(file);
  }

  const manifest: BrandManifest = {
    version: 1,
    capture: {
      clock: captureClock,
      deviceScaleFactor: 2,
      locale: "en-US",
      timezone: "UTC",
    },
    sources,
    outputs: {
      "docs/screenshots/inbox.png": inbox,
      "docs/screenshots/session.png": session,
      "docs/brand/banner.png": banner,
    },
  };

  await mkdir(dirname(manifestPath()), { recursive: true });
  await writeManifest(manifest);

  console.log("brand:screens updated");
  for (const [path, spec] of Object.entries(outputSpecs)) {
    const output = manifest.outputs[path];
    console.log(`  ${path}  ${output.width}x${output.height}`);
  }
  console.log(`  ${resolve(repoRoot, "docs/brand/manifest.json")}`);
  console.log(
    "Icons are not regenerated by this command. If the mark or fixed palette changed, see Regenerate icons.",
  );
} finally {
  await resizePage.close();
  await browser.close();
  await server.close();
}
